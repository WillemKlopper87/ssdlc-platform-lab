#!/usr/bin/env python3
"""
policy-eval/evaluate-findings.py

The severity-threshold gate DESIGN.md's roadmap calls "the project" for
Milestone 3: reads each scanner's raw report, normalizes it through
normalise/*_adapter.py (docs/adr/0018), and evaluates the combined
finding list against policy/severity.rego via Conftest -- one reviewable
policy file, not blocking logic scattered across each scanner's own
--exit-code flag the way pipelines/fast.woodpecker.yml did before this
existed.

Exit 0: no new Critical/High findings (Medium/Low are logged, not blocking,
        per framework §2.4 -- matches DESIGN.md's severity table exactly).
Exit 1: at least one new Critical or High finding -- stdout lists every
        one, with its severity, tool, rule, and location, so a developer
        knows exactly what to fix without opening a separate dashboard.
Exit 2: could not evaluate at all (a scanner report is malformed, or
        Conftest itself fails to run) -- fails closed, matching every
        other gate step in this project (D4: no terminal status, no
        "success").

docs/adr/0024: baseline/differential gating. A finding whose (tool,
fingerprint) pair appears in --baseline (default .ssdlc/baseline.json,
generated by scripts/generate-baseline.py) does not block -- it is
pre-existing debt, printed separately as informational, not silently
dropped. DESIGN.md's own rule applies unconditionally: secrets are
NEVER baselined, regardless of what the baseline file says -- a Gitleaks
finding always evaluates as new. A missing baseline file means an empty
baseline (every finding is "new"), which is exactly this script's
original, still-current behaviour for any repo onboarded before this
feature existed -- fully backward compatible, not a breaking change.

A malformed or unreadable baseline file is treated as an EMPTY baseline
(logged, not fatal) rather than exit 2. This is deliberate and asymmetric
with a malformed SCANNER report (which stays fatal): losing the baseline
means "evaluate everything as new," the strictly safer failure direction,
never "treat everything as already accepted."

The baseline file itself is gate-managed (scripts/bot-approver.py's
DEFAULT_GATE_MANAGED_PATHS) -- a PR cannot add its own new finding to the
baseline and expect the bot's protected-base comparison to miss it.

Usage (each report path is optional -- a scanner that found nothing, or
wasn't run this pipeline, is not an error):
  python3 evaluate-findings.py \
    --gitleaks gitleaks-report.json \
    --semgrep semgrep-report.json \
    --trivy trivy-report.json \
    --baseline .ssdlc/baseline.json
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
NORMALISE_DIR = os.path.join(SCRIPT_DIR, "..", "normalise")
POLICY_DIR = os.path.join(SCRIPT_DIR, "..", "policy")
CONFTEST_BIN = os.environ.get("CONFTEST_BIN", "conftest")

sys.path.insert(0, NORMALISE_DIR)
import gitleaks_adapter  # noqa: E402
import semgrep_adapter  # noqa: E402
import trivy_adapter  # noqa: E402


def load_report(path):
    if not path or not os.path.exists(path):
        return None
    with open(path) as fh:
        content = fh.read().strip()
    return json.loads(content) if content else None


def collect_findings(args):
    findings = []

    gitleaks_data = load_report(args.gitleaks)
    if gitleaks_data is not None:
        findings += gitleaks_adapter.normalize(gitleaks_data)

    semgrep_data = load_report(args.semgrep)
    if semgrep_data is not None:
        findings += semgrep_adapter.normalize(semgrep_data.get("results", []), args.semgrep_root)

    trivy_data = load_report(args.trivy)
    if trivy_data is not None:
        findings += trivy_adapter.normalize(trivy_data.get("Results"))

    return findings


def load_baseline(path):
    """Return a set of (tool, fingerprint) pairs, or an empty set for any
    condition short of a genuinely well-formed baseline file -- missing,
    empty, malformed, or structurally wrong all collapse to "no baseline",
    never to "trust it anyway". Logs which case it was, since a silently
    empty baseline (e.g. a typo'd path) should be visible to whoever is
    debugging why nothing is baselined.
    """
    if not path or not os.path.exists(path):
        return set()
    try:
        with open(path, encoding="utf-8") as fh:
            document = json.load(fh)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"policy-eval: WARNING: baseline {path} unreadable ({exc}) -- treating as empty", file=sys.stderr)
        return set()

    entries = document.get("findings") if isinstance(document, dict) else None
    if not isinstance(entries, list):
        print(f"policy-eval: WARNING: baseline {path} has no 'findings' list -- treating as empty", file=sys.stderr)
        return set()

    pairs = set()
    for entry in entries:
        if isinstance(entry, dict) and isinstance(entry.get("tool"), str) and isinstance(entry.get("fingerprint"), str):
            pairs.add((entry["tool"], entry["fingerprint"]))
        else:
            print(f"policy-eval: WARNING: baseline {path} has a malformed entry -- skipping it, not the whole file", file=sys.stderr)
    return pairs


def split_baseline(findings, baseline_pairs):
    """Return (new_findings, baseline_findings). Secrets are never
    baselined -- DESIGN.md D7's rule, applied here unconditionally
    regardless of what the baseline file itself claims."""
    new_findings, baseline_findings = [], []
    for f in findings:
        if f["tool"] != "gitleaks" and (f["tool"], f["fingerprint"]) in baseline_pairs:
            baseline_findings.append(f)
        else:
            new_findings.append(f)
    return new_findings, baseline_findings


def run_conftest(findings):
    """Returns (exit_code_ok, warnings, failures). Conftest needs a real
    file, not stdin, for --output=json to behave predictably -- confirmed
    live rather than assumed, matching every other tool integration in
    this project."""
    if not findings:
        return True, [], []

    with tempfile.NamedTemporaryFile(mode="w", suffix=".json", delete=False) as tmp:
        json.dump(findings, tmp)
        tmp_path = tmp.name

    try:
        try:
            result = subprocess.run(
                [CONFTEST_BIN, "test", "--policy", POLICY_DIR, "--output=json", tmp_path],
                capture_output=True, text=True,
            )
        except OSError as exc:
            print(f"policy-eval: FATAL: could not start conftest: {exc}", file=sys.stderr)
            sys.exit(2)
        # conftest exits 1 when there are failures -- that is success for
        # THIS script's purposes (it means conftest ran correctly and
        # found something); only a genuine crash (no parseable JSON) is
        # a fatal evaluation error.
        if result.returncode not in (0, 1):
            print(
                f"policy-eval: FATAL: conftest exited {result.returncode}:\n{result.stdout}\n{result.stderr}",
                file=sys.stderr,
            )
            sys.exit(2)

        try:
            data = json.loads(result.stdout) if result.stdout.strip() else []
        except json.JSONDecodeError:
            print(f"policy-eval: FATAL: conftest produced unparseable output:\n{result.stdout}\n{result.stderr}", file=sys.stderr)
            sys.exit(2)

        warnings, failures = [], []
        for entry in data:
            warnings += [w["msg"] for w in entry.get("warnings", [])]
            failures += [f["msg"] for f in entry.get("failures", [])]
        return True, warnings, failures
    finally:
        os.unlink(tmp_path)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gitleaks", default=os.environ.get("GITLEAKS_REPORT", "gitleaks-report.json"))
    parser.add_argument("--semgrep", default=os.environ.get("SEMGREP_REPORT", "semgrep-report.json"))
    parser.add_argument("--trivy", default=os.environ.get("TRIVY_REPORT", "trivy-report.json"))
    parser.add_argument("--baseline", default=os.environ.get("BASELINE_REPORT", ".ssdlc/baseline.json"))
    # docs/adr/0025: the fast gate scans "." (Semgrep already returns
    # scan-root-relative paths, so no root is needed there -- the default).
    # A caller whose Semgrep invocation used an absolute or container-
    # mount-point target (scripts/generate-baseline.py, gate-bundle/
    # run-pilot-bundle.py) MUST pass the same value here, or every Semgrep
    # fingerprint it computes silently disagrees with every other scan
    # site's -- see normalise/semgrep_adapter.py's docstring for the live
    # evidence this was found from.
    parser.add_argument("--semgrep-root", default=os.environ.get("SEMGREP_ROOT"))
    args = parser.parse_args()

    try:
        findings = collect_findings(args)
    except (OSError, ValueError, TypeError, KeyError) as exc:
        print(f"policy-eval: FATAL: could not read or normalize scanner report: {exc}", file=sys.stderr)
        return 2

    baseline_pairs = load_baseline(args.baseline)
    new_findings, baseline_findings = split_baseline(findings, baseline_pairs)

    by_severity = {"critical": 0, "high": 0, "medium": 0, "low": 0}
    for f in findings:
        by_severity[f["severity"]] = by_severity.get(f["severity"], 0) + 1

    print(
        f"policy-eval: {len(findings)} finding(s) normalized -- "
        f"critical={by_severity['critical']} high={by_severity['high']} "
        f"medium={by_severity['medium']} low={by_severity['low']}"
    )
    if baseline_pairs:
        print(
            f"policy-eval: {len(baseline_findings)} finding(s) match the baseline "
            f"({args.baseline}) -- pre-existing debt, not evaluated for blocking"
        )
        for b in baseline_findings:
            print(f"  BASELINE  [{b['tool']}/{b['rule_id']}] {b['file']}:{b.get('line', '?')} -- {b['message']}")

    _, warnings, failures = run_conftest(new_findings)

    for w in warnings:
        print(f"  WARN  {w}")
    for f in failures:
        print(f"  FAIL  {f}")

    if failures:
        print(f"policy-eval: FAIL -- {len(failures)} new Critical/High finding(s) block the merge")
        return 1

    print("policy-eval: PASS -- no new Critical/High findings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
